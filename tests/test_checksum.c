#include "checksum.h"

#include <arpa/inet.h>
#include <assert.h>
#include <stdint.h>
#include <stdio.h>

int main(void)
{
    uint8_t header[] = {
        0x45, 0x00, 0x00, 0x73,
        0x00, 0x00, 0x40, 0x00,
        0x40, 0x11, 0x00, 0x00,
        0xc0, 0xa8, 0x00, 0x01,
        0xc0, 0xa8, 0x00, 0xc7
    };

    uint16_t checksum = ipv4_checksum(header, sizeof(header));

    assert(ntohs(checksum) == 0xb861);

    printf("IPv4 checksum test passed\n");

    uint8_t tcp_packet[40] = {
        0x45, 0x00, 0x00, 0x28,
        0x00, 0x01, 0x40, 0x00,
        0x40, 0x06, 0x00, 0x00,
        0xc0, 0x00, 0x02, 0x01,
        0xc6, 0x33, 0x64, 0x02,
        0x30, 0x39, 0x00, 0x50,
        0x00, 0x00, 0x00, 0x01,
        0x00, 0x00, 0x00, 0x00,
        0x50, 0x02, 0x40, 0x00,
        0x00, 0x00, 0x00, 0x00
    };

    uint16_t tcp_result = tcp_checksum(
        tcp_packet,
        sizeof(tcp_packet)
    );

    assert(ntohs(tcp_result) == 0x5321);

    printf("TCP checksum test passed\n");

    return 0;
}
